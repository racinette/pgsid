func float8Power(left, right SqlFloat) SqlFloat {
	if left.Error != "" {
		return left
	}
	if right.Error != "" {
		return right
	}
	if !left.Valid || !right.Valid {
		return SqlFloat{}
	}
	x, y := left.Value, right.Value
	if math.IsNaN(x) {
		if y == 0 {
			return SqlFloat{Value: 1, Valid: true}
		}
		return SqlFloat{Value: math.NaN(), Valid: true}
	}
	if math.IsNaN(y) {
		if x == 1 {
			return SqlFloat{Value: 1, Valid: true}
		}
		return SqlFloat{Value: math.NaN(), Valid: true}
	}
	if x == 0 && y < 0 || x < 0 && math.Floor(y) != y {
		return SqlFloat{Error: "2201F"}
	}
	if math.IsInf(y, 0) {
		a := math.Abs(x)
		if a == 1 {
			return SqlFloat{Value: 1, Valid: true}
		}
		if a > 1 == (y > 0) {
			return SqlFloat{Value: math.Inf(1), Valid: true}
		}
		return SqlFloat{Value: 0, Valid: true}
	}
	odd := math.Abs(math.Mod(y, 2)) == 1
	if y == 0 {
		return SqlFloat{Value: 1, Valid: true}
	}
	if math.IsInf(x, 0) {
		if y > 0 {
			if x < 0 && odd {
				return SqlFloat{Value: math.Inf(-1), Valid: true}
			}
			return SqlFloat{Value: math.Inf(1), Valid: true}
		}
		result := 0.0
		if x < 0 && odd {
			result = math.Copysign(0, -1)
		}
		return SqlFloat{Value: result, Valid: true}
	}
	if x == 0 {
		result := 0.0
		if math.Signbit(x) && odd {
			result = math.Copysign(0, -1)
		}
		return SqlFloat{Value: result, Valid: true}
	}
	result := sqlFloatPowerKernel(x, y)
	if math.IsInf(result, 0) || result == 0 {
		return SqlFloat{Error: "22003"}
	}
	return SqlFloat{Value: result, Valid: true}
}
