// musl's log10 keeps fdlibm's algorithm: the argument is reduced into [sqrt(2)/2, sqrt(2)]
// through its high word, and the result is accumulated in high and low parts.
fn musl_log10(input: f64) -> f64 {
    if input == 1.0f64 {
        return 0.0f64;
    };
    let mut x = input;
    let mut k: i64 = 0i64;
    let mut bits = x.to_bits() as i64;
    let mut hx = bits / 4294967296i64;
    if hx < 1048576i64 {
        k = k - 54i64;
        x = x * 18014398509481984.0f64;
        bits = x.to_bits() as i64;
        hx = bits / 4294967296i64;
    };
    let low = bits % 4294967296i64;
    hx = hx + 1072693248i64 - 1072079006i64;
    k = k + hx / 1048576i64 - 1023i64;
    hx = hx % 1048576i64 + 1072079006i64;
    x = f64::from_bits((hx * 4294967296i64 + low) as u64);
    let f = x - 1.0f64;
    let hfsq = 0.5f64 * f * f;
    let s = f / (2.0f64 + f);
    let z = s * s;
    let mut w = z * z;
    let t1 = w
        * (3.999999999940941908e-01f64
            + w * (2.222219843214978396e-01f64 + w * 1.531383769920937332e-01f64));
    let t2 = z
        * (6.666666666666735130e-01f64
            + w * (2.857142874366239149e-01f64
                + w * (1.818357216161805012e-01f64 + w * 1.479819860511658591e-01f64)));
    let r = t2 + t1;
    let hi = float8_clear_low_word(f - hfsq);
    let lo = f - hi - hfsq + s * (hfsq + r);
    let mut val_hi = hi * 4.34294481878168880939e-01f64;
    let dk = (k as i32) as f64;
    let y = dk * 3.01029995663611771306e-01f64;
    let mut val_lo = dk * 3.69423907715893078616e-13f64
        + (lo + hi) * 2.50829467116452752298e-11f64
        + lo * 4.34294481878168880939e-01f64;
    w = y + val_hi;
    // C's `val_lo += (y - w) + val_hi` adds the whole right-hand side at once.
    val_lo = val_lo + ((y - w) + val_hi);
    val_hi = w;
    val_lo + val_hi
}

