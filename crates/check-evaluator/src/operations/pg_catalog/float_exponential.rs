// musl's cbrt: a rough root from the high word divided by three, a polynomial refinement to 23
// bits, rounding away from zero to 23 bits, and one Newton step. Bit fields are handled on the
// magnitude and the sign restored, as each step preserves the sign of the argument.
fn musl_cbrt(x: f64) -> f64 {
    let bits = x.to_bits() as i64;
    let negative = bits < 0i64;
    let mut high = circle_math_high_word(x) as i64;
    if high >= 2146435072i64 {
        return x + x;
    };
    if high < 1048576i64 {
        let scaled = x * 18014398509481984.0f64;
        high = circle_math_high_word(scaled) as i64;
        if high == 0i64 {
            return x;
        };
        high = high / 3i64 + 696219795i64;
    } else {
        high = high / 3i64 + 715094163i64;
    };
    let mut t = f64::from_bits((high * 4294967296i64) as u64);
    if negative {
        t = -t;
    };
    let mut r = (t * t) * (t / x);
    t = t
        * ((1.87595182427177009643f64
            + r * (-1.88497979543377169875f64 + r * 1.621429720105354466140f64))
            + ((r * r) * r) * (-0.758397934778766047437f64 + r * 0.145996192886612446982f64));
    let mut magnitude = t.to_bits() as i64;
    if magnitude < 0i64 {
        magnitude = magnitude - (0i64 - 9223372036854775807i64 - 1i64);
    };
    magnitude = magnitude + 2147483648i64;
    magnitude = magnitude - magnitude % 1073741824i64;
    t = f64::from_bits(magnitude as u64);
    if negative {
        t = -t;
    };
    let s = t * t;
    r = x / s;
    let w = t + t;
    r = (r - t) / (w + r);
    t + t * r
}

