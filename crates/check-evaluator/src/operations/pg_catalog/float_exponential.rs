// The dialect casts only small integer types to usize, so table indices below a few hundred are
// counted up instead.
fn musl_index(value: i64) -> usize {
    let mut index: usize = 0;
    let mut remaining = value;
    while remaining > 0i64 {
        index += 1;
        remaining = remaining - 1i64;
    }
    index
}

// Transcribed from musl's exp and log (Arm optimized-routines, MIT licence) without FMA, as built
// for WebAssembly. The dialect has no bitwise operators or unsigned integers, so bit fields are
// split arithmetically; the table entries already compensate for the low index bits, so a scale
// is the entry plus j * 2^45 + q * 2^52 for k = 128q + j.
fn musl_top12(x: f64) -> i64 {
    (circle_math_high_word(x) / 1048576) as i64
}

fn musl_exp_special(tmp: f64, base: i64, quotient: i64, positive: bool) -> f64 {
    if positive {
        let scale = f64::from_bits((base + (quotient - 1009i64) * 4503599627370496i64) as u64);
        return 5.486124068793689e+303f64 * (scale + scale * tmp);
    };
    let scale = f64::from_bits((base + (quotient + 1022i64) * 4503599627370496i64) as u64);
    let mut y = scale + scale * tmp;
    if y < 1.0f64 {
        let mut lo = scale - y + scale * tmp;
        let hi = 1.0f64 + y;
        lo = 1.0f64 - hi + y + lo;
        y = (hi + lo) - 1.0f64;
        if y == 0.0f64 {
            y = 0.0f64;
        };
    };
    2.2250738585072014e-308f64 * y
}

fn musl_exp(x: f64) -> f64 {
    let mut abstop = musl_top12(x);
    if abstop < 969i64 || abstop >= 1032i64 {
        if abstop < 969i64 {
            return 1.0f64 + x;
        };
        if abstop >= 1033i64 {
            if x == -1.0f64 / 0.0f64 {
                return 0.0f64;
            };
            if abstop >= 2047i64 {
                return 1.0f64 + x;
            };
            if x < 0.0f64 {
                return 0.0f64;
            };
            return 1.0f64 / 0.0f64;
        };
        abstop = 0i64;
    };
    let z = 184.6649652337873f64 * x;
    let mut kd = z + 6755399441055744.0f64;
    let ki = kd.to_bits() as i64;
    kd = kd - 6755399441055744.0f64;
    let r = x + kd * -0.005415212348111709f64 + kd * -1.2864023111638346e-14f64;
    let k = ki - 4843621399236968448i64;
    let j = ((k % 128i64) + 128i64) % 128i64;
    let quotient = (k - j) / 128i64;
    let index = musl_index(2i64 * j);
    let tail = f64::from_bits(MUSL_EXP_TABLE[index] as u64);
    let base = MUSL_EXP_TABLE[index + 1] + j * 35184372088832i64;
    let r2 = r * r;
    let tmp = tail
        + r
        + r2 * (f64::from_bits(MUSL_EXP_POLY[0] as u64)
            + r * f64::from_bits(MUSL_EXP_POLY[1] as u64))
        + r2 * r2
            * (f64::from_bits(MUSL_EXP_POLY[2] as u64)
                + r * f64::from_bits(MUSL_EXP_POLY[3] as u64));
    if abstop == 0i64 {
        return musl_exp_special(tmp, base, quotient, k > 0i64);
    };
    let scale = f64::from_bits((base + quotient * 4503599627370496i64) as u64);
    scale + scale * tmp
}

// Arguments are positive and finite; PostgreSQL rejects others first.
fn musl_log(input: f64) -> f64 {
    let mut ix = input.to_bits() as i64;
    if ix - 4606619468846596096i64 < 4607473789381378048i64 - 4606619468846596096i64
        && ix >= 4606619468846596096i64
    {
        if input == 1.0f64 {
            return 0.0f64;
        };
        let r = input - 1.0f64;
        let r2 = r * r;
        let r3 = r * r2;
        let mut y = r3
            * (f64::from_bits(MUSL_LOG_POLY1[1] as u64)
                + r * f64::from_bits(MUSL_LOG_POLY1[2] as u64)
                + r2 * f64::from_bits(MUSL_LOG_POLY1[3] as u64)
                + r3 * (f64::from_bits(MUSL_LOG_POLY1[4] as u64)
                    + r * f64::from_bits(MUSL_LOG_POLY1[5] as u64)
                    + r2 * f64::from_bits(MUSL_LOG_POLY1[6] as u64)
                    + r3 * (f64::from_bits(MUSL_LOG_POLY1[7] as u64)
                        + r * f64::from_bits(MUSL_LOG_POLY1[8] as u64)
                        + r2 * f64::from_bits(MUSL_LOG_POLY1[9] as u64)
                        + r3 * f64::from_bits(MUSL_LOG_POLY1[10] as u64))));
        let mut w = r * 134217728.0f64;
        let rhi = r + w - w;
        let rlo = r - rhi;
        w = rhi * rhi * f64::from_bits(MUSL_LOG_POLY1[0] as u64);
        let hi = r + w;
        let mut lo = r - hi + w;
        lo = lo + f64::from_bits(MUSL_LOG_POLY1[0] as u64) * rlo * (rhi + r);
        y = y + lo;
        y = y + hi;
        return y;
    };
    if ix < 4503599627370496i64 {
        ix = (input * 4503599627370496.0f64).to_bits() as i64 - 234187180623265792i64;
    };
    let tmp = ix - 4604367669032910848i64;
    // An unsigned shift of the difference is a floor division of its signed value.
    let mut step = tmp / 35184372088832i64;
    if tmp < 0i64 && tmp % 35184372088832i64 != 0i64 {
        step = step - 1i64;
    };
    let i = (step % 128i64 + 128i64) % 128i64;
    let mut k = tmp / 4503599627370496i64;
    if tmp < 0i64 && tmp % 4503599627370496i64 != 0i64 {
        k = k - 1i64;
    };
    let iz = ix - k * 4503599627370496i64;
    let invc = f64::from_bits(MUSL_LOG_TABLE[musl_index(2i64 * i)] as u64);
    let logc = f64::from_bits(MUSL_LOG_TABLE[musl_index(2i64 * i + 1i64)] as u64);
    let z = f64::from_bits(iz as u64);
    let r = (z
        - f64::from_bits(MUSL_LOG_TABLE2[musl_index(2i64 * i)] as u64)
        - f64::from_bits(MUSL_LOG_TABLE2[musl_index(2i64 * i + 1i64)] as u64))
        * invc;
    let kd = (k as i32) as f64;
    let w = kd * 0.6931471805598903f64 + logc;
    let hi = w + r;
    let lo = w - hi + r + kd * 5.497923018708371e-14f64;
    let r2 = r * r;
    lo + r2 * f64::from_bits(MUSL_LOG_POLY[0] as u64)
        + r * r2
            * (f64::from_bits(MUSL_LOG_POLY[1] as u64)
                + r * f64::from_bits(MUSL_LOG_POLY[2] as u64)
                + r2 * (f64::from_bits(MUSL_LOG_POLY[3] as u64)
                    + r * f64::from_bits(MUSL_LOG_POLY[4] as u64)))
        + hi
}

