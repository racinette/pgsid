// Clears the low 27 bits of a bit pattern, keeping its sign: `asdouble(bits & -1ULL << 27)`.
fn musl_clear_low_27(value: f64) -> f64 {
    let bits = value.to_bits() as i64;
    let low = ((bits % 134217728i64) + 134217728i64) % 134217728i64;
    f64::from_bits((bits - low) as u64)
}

// The 12 top bits including the sign, as an unsigned value.
fn musl_top12_signed(x: f64) -> i64 {
    let bits = x.to_bits() as i64;
    if bits < 0i64 {
        return (bits - (0i64 - 9223372036854775807i64 - 1i64)) / 4503599627370496i64 + 2048i64;
    };
    bits / 4503599627370496i64
}

// 0 for a non-integer, 1 for an odd integer and 2 for an even integer.
fn musl_checkint(y: f64) -> i32 {
    let magnitude = y.abs().to_bits() as i64;
    let exponent = magnitude / 4503599627370496i64;
    if exponent < 1023i64 {
        return 0;
    };
    if exponent > 1075i64 {
        return 2;
    };
    let mut unit: i64 = 1i64;
    let mut shift: i64 = 1075i64 - exponent;
    while shift > 0i64 {
        unit = unit * 2i64;
        shift = shift - 1i64;
    }
    if magnitude % unit != 0i64 {
        return 0;
    };
    if (magnitude / unit) % 2i64 == 1i64 {
        return 1;
    };
    2
}

// pow's exp_inline with an extra tail; a negative sign is applied to the final result, since
// the sign bit only flips the scale and every later step is symmetric.
fn musl_pow_exp(x: f64, xtail: f64, negative: bool) -> f64 {
    let mut abstop = musl_top12(x);
    let mut result = 0.0f64;
    if abstop < 969i64 || abstop >= 1032i64 {
        if abstop < 969i64 {
            result = 1.0f64 + x;
            if negative {
                return -result;
            };
            return result;
        };
        if abstop >= 1033i64 {
            result = 1.0f64 / 0.0f64;
            if x < 0.0f64 {
                result = 0.0f64;
            };
            if negative {
                return -result;
            };
            return result;
        };
        abstop = 0i64;
    };
    let z = 184.6649652337873f64 * x;
    let mut kd = z + 6755399441055744.0f64;
    let ki = kd.to_bits() as i64;
    kd = kd - 6755399441055744.0f64;
    let mut r = x + kd * -0.005415212348111709f64 + kd * -1.2864023111638346e-14f64;
    r = r + xtail;
    let k = ki - 4843621399236968448i64;
    let j = ((k % 128i64) + 128i64) % 128i64;
    let quotient = (k - j) / 128i64;
    let index = musl_index(2i64 * j);
    let tail = f64::from_bits(MUSL_EXP_TABLE[index] as u64);
    let base = MUSL_EXP_TABLE[index + 1] + j * 35184372088832i64;
    let r2 = r * r;
    let tmp = tail
        + r
        + r2 * (f64::from_bits(MUSL_EXP_POLY[0] as u64)
            + r * f64::from_bits(MUSL_EXP_POLY[1] as u64))
        + r2 * r2
            * (f64::from_bits(MUSL_EXP_POLY[2] as u64)
                + r * f64::from_bits(MUSL_EXP_POLY[3] as u64));
    if abstop == 0i64 {
        result = musl_exp_special(tmp, base, quotient, k >= 0i64);
    } else {
        let scale = f64::from_bits((base + quotient * 4503599627370496i64) as u64);
        result = scale + scale * tmp;
    };
    if negative {
        return -result;
    };
    result
}

