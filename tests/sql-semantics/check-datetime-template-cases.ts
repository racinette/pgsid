import type { PGlite } from '@electric-sql/pglite'

export async function datetimeTemplatePairs(pg: PGlite): Promise<Array<[string, string]>> {
  const pairs: Array<[string, string]> = []
  const add = (a: string, b: string) => pairs.push([a, b])
  for (const template of [
    '',
    'YYYY-MM-DD',
    'FXYYYY-MM-DD',
    'YYYYMMDD',
    'YYYY/MM/DD',
    'YYYY MM DD',
    'YYYY"x"MM"y"DD',
    'FMYYYYFMMMFMDD',
    'YYYY-DDD',
    'IYYY-IW-ID',
    'IYYY-IDDD',
    'YYYY WW D',
    'YYYY MM W',
    'Y,YYY-MM-DD',
    'CC YY-MM-DD',
    'YYYY-MM-DD BC',
    'YYYY-MM-DD HH24:MI:SS.US',
    'YYYY-MM-DD HH12:MI:SS AM',
    'YYYY-MM-DD HH24:MI:SS.FF1',
    'YYYY-MM-DD HH24:MI:SS.FF3',
    'YYYY-MM-DD HH24:MI:SS TZH:TZM',
    'YYYY-MM-DD HH24:MI:SS OF',
    'YYYY-MM-DD HH24:MI:SS TZ',
    'MONTH DD YYYY',
    'TMMonth DD YYYY',
    'DY MON DD YYYY',
    'YYYY-MM-DDTHH24:MI:SS',
    '"quoted"YYYY-MM-DD',
  ]) {
    for (const text of [
      '2000-12-31 23:59:59.123456',
      '2024-02-29 12:00:00.000000',
      '0001-01-01 00:00:00 BC',
      '4714-11-24 00:00:00 BC',
      '294276-12-31 23:59:59.999999',
    ]) {
      try {
        const { v } = (
          await pg.query<{ v: string }>('SELECT to_char($1::timestamp,$2) v', [text, template])
        ).rows[0]!
        if (v !== null) {
          add(v, template)
          add(v + 'trail', template)
          add(' ' + v, template)
          add(v.slice(0, Math.max(1, v.length - 3)), template)
        }
      } catch {}
    }
  }
  const words = [
    'YYYY',
    'YYY',
    'YY',
    'Y',
    'Y,YYY',
    'IYYY',
    'IYY',
    'IY',
    'I',
    'CC',
    'MM',
    'DD',
    'DDD',
    'IDDD',
    'WW',
    'IW',
    'W',
    'Q',
    'J',
    'RM',
    'HH',
    'HH12',
    'HH24',
    'MI',
    'SS',
    'SSSS',
    'SSSSS',
    'MS',
    'US',
    'FF1',
    'FF2',
    'FF3',
    'FF4',
    'FF5',
    'FF6',
    'AM',
    'A.M.',
    'PM',
    'P.M.',
    'FX',
    'MONTH',
    'Month',
    'MON',
    'Mon',
    'DAY',
    'Day',
    'DY',
    'Dy',
    'D',
    'ID',
    'AD',
    'A.D.',
    'BC',
    'B.C.',
    'TZ',
    'TZH',
    'TZM',
    'OF',
  ]
  for (const word of [
    ...new Set(
      words.flatMap((word) => [word, word.toLowerCase(), 'FM' + word, word + 'TH', 'TM' + word]),
    ),
  ])
    for (const input of [
      '',
      ' ',
      '0',
      '1',
      '12',
      '24',
      '123',
      '2024',
      '-1',
      '+1',
      '01',
      '0000',
      '1234567',
      '2147483647',
      '2147483648',
      '-2147483648',
      'January',
      'Jan',
      'Sunday',
      'Sun',
      'XII',
      'PM',
      'AD',
      'BC',
      'UTC',
      'GMT',
      'EST',
      'EDT',
      'MSK',
      'AEST',
      '+02:30',
      '-00:30',
      'xxx',
      'é',
      ' é',
    ])
      add(input, word)
  for (const pair of [
    ['2024-02-29', 'YYYY-MM-DD'],
    ['2023-02-29', 'YYYY-MM-DD'],
    ['2024-00-00', 'YYYY-MM-DD'],
    ['2024', 'YYYY-MM-DD'],
    ['2024x02y29', 'FXYYYY-MM-DD'],
    ['2024x02y29', 'YYYY-MM-DD'],
    ['20240229', 'YYYY-MM-DD'],
    ['2024 02 29', 'YYYY"x"MM"x"DD'],
    ['2024--02--29', 'YYYY-MM-DD'],
    ['4714-11-23 23:00 -02 BC', 'YYYY-MM-DD HH24:MI TZH BC'],
    ['294277-01-01 00:00 +01', 'YYYY-MM-DD HH24:MI TZH'],
    ['5874897-12-31', 'YYYY-MM-DD'],
    ['5874898-01-01', 'YYYY-MM-DD'],
    ['2024-11-03 01:30 EST', 'YYYY-MM-DD HH24:MI TZ'],
    ['2024-11-03 01:30 EDT', 'YYYY-MM-DD HH24:MI TZ'],
    ['2024-03-10 02:30 EST', 'YYYY-MM-DD HH24:MI TZ'],
    ['2024-03-10 02:30 EDT', 'YYYY-MM-DD HH24:MI TZ'],
    ['2024-01-01 UTCFOO', 'YYYY-MM-DD TZ'],
    ['2024-01-01 GMT+03', 'YYYY-MM-DD TZ'],
    ['2024-01-01 -02', 'YYYY-MM-DD TZH'],
    ['2024-01-01   -02', 'YYYY-MM-DD   TZH'],
    ['-2147483 -2147483647', 'MS US'],
    ['2147483 2147483647', 'MS US'],
    ['-2147483 2147483000', 'MS US'],
    [' é', 'FXMM"1"'],
    [' é', 'FXMMDD'],
    ['001 1', 'MS MS'],
    ['1 1', 'MS MS'],
    ['001 1', 'US US'],
    ['1 1', 'US US'],
    ['2024 24', 'YYYY YY'],
    ['24 2024', 'YY YYYY'],
    ['Monday Monday', 'DAY DAY'],
    ['Sunday Sunday', 'DAY DAY'],
    ['2024-01-01 16:00', 'YYYY-MM-DD HH24:MI'],
    ['23 11', 'HH24 HH12'],
    ['11 23', 'HH12 HH24'],
    ['2024-01-01 25:00 +99', 'YYYY-MM-DD HH24:MI TZH'],
    ['2024-01-01 +99', 'YYYY-MM-DD TZH'],
    ['2024-01-01 +02 UTC', 'YYYY-MM-DD TZH TZ'],
    ['2024-01-01 UTC +02', 'YYYY-MM-DD TZ TZH'],
  ] as Array<[string, string]>)
    add(...pair)
  for (const pair of [
    ['-2147483 -2147483647', 'FXMS US'],
    ['-2147483 -2147483648', 'FXMS US'],
    ['-2147483648', 'FXUS'],
    ['2,024', 'Y,YYY'],
    ['-2147483648,000', 'Y,YYY'],
    ['2147483648,000', 'Y,YYY'],
    ['2024-02-29', 'FXYYYY-MM-DD'],
    ['2024-02-29', 'FXFXYYYY-MM-DD'],
    ['2024+2+29', 'FXYYYY-MM-DD'],
    ['2024   -02', 'YYYY TZH'],
    ['2024-02', 'YYYY TZH'],
    ['2024 -02', 'YYYY  TZH'],
    ['2024 -02', 'YYYY"x"TZH'],
    ['12', 'FXMMDD'],
    [' 12', 'FXMMDD'],
    [' é', 'FXMMDD'],
    [' 1é', 'FXMMDD'],
    [' é12', 'FXMMDD'],
    ['2024-01-01 MSK', 'YYYY-MM-DD TZ'],
    ['2024-01-01 BST', 'YYYY-MM-DD TZ'],
    ['2024-01-01 ABC', 'YYYY-MM-DD TZ'],
    ['2024-01-01 BCD', 'YYYY-MM-DD TZ'],
    ['2024-01-01 ABCDE', 'YYYY-MM-DD TZ'],
    ['1', 'FMFMYYYY'],
    ['1', 'TMTMYYYY'],
    ['1', 'FM"YYYY"YYYY'],
    ['1', '\\YYYY'],
  ] as Array<[string, string]>)
    add(...pair)

  return [...new Map(pairs.map((pair) => [JSON.stringify(pair), pair])).values()]
}
